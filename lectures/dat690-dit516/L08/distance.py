'''
We have a standalone function get_distance which we want to test for a range of input generated by hypothesis library. 

Note that the function definition has two parameters a,b. But when we call the function, we do not pass any arguments. 

The @gv (given decorator) generates these two parameters randomly with st (strategies) several times, and calls get_distance with them.  
'''
from hypothesis import given as gv, strategies as st

pos = st.tuples( st.floats(10.9, 24.0), st.floats(55.3, 69.1) )

@gv(a=pos, b=pos)
def get_distance(a, b):
    (x1, y1) = a
    (x2, y2) = b

    # print(a, b)
    # print( ((x2-x1)**2 + (y2-y1)**2)**0.5) 
    return ((x2-x1)**2 + (y2-y1)**2)**0.5

print(get_distance())

